#!/usr/bin/env node
import { createHash } from "node:crypto";
import { readdir, readFile } from "node:fs/promises";
import path from "node:path";

const apiBaseUrl = process.env.MAIKS_API_BASE_URL ?? "http://localhost:3001";
const manifestVersion = "youtube-audio-library.v1";
const ccBy4Url = "https://creativecommons.org/licenses/by/4.0/";
const sha256Pattern = /^[a-f0-9]{64}$/u;
const musicAudioStorageRefPattern = /^music-audio:([a-f0-9]{64}):[A-Za-z0-9._:-]+$/u;
const safeVocalsClasses = new Set(["none", "minimal"]);

const usage = `
Usage:
  node scripts/import-youtube-audio-library.mjs --manifest ./.private/youtube-audio-library-export/youtube-audio-library-manifest.json --audio-dir ./.private/youtube-audio-library-export/audio --token <owner-token> [--apply]

Options:
  --manifest       Typed JSON manifest, usually generated by scripts/export-youtube-audio-library-studio.mjs.
  --audio-dir      Directory containing downloaded audio files referenced by the generated manifest.
  --token          Owner bearer/dev token. Can also use MAIKS_OWNER_BEARER_TOKEN or MAIKS_DEV_AUTH_TOKEN.
  --api-base-url   API base URL. Defaults to MAIKS_API_BASE_URL or http://localhost:3001.
  --apply          Apply the catalog import. Without this flag, the script calls dry-run.
  --refresh-mode   full or partial. Defaults to the manifest value, or partial for ad hoc CSV/JSON input.
  --no-upload      Do not upload files; manifest rows must already contain audio.storageRef and audio.sha256.

Workflow:
  1. Run scripts/export-youtube-audio-library-studio.mjs with a current YouTube Studio Audio Library page.
  2. Run this script first as a dry-run, then repeat with --apply after reviewing the summary.
`;

const parseArgs = () => {
  const args = process.argv.slice(2);
  const parsed = {
    apply: false,
    refreshMode: null,
    upload: true
  };

  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];

    if (arg === "--apply") {
      parsed.apply = true;
      continue;
    }
    if (arg === "--no-upload") {
      parsed.upload = false;
      continue;
    }

    const next = args[index + 1];
    if (!next) {
      throw new Error(`Missing value for ${arg}`);
    }

    if (arg === "--manifest") {
      parsed.manifest = next;
    } else if (arg === "--audio-dir") {
      parsed.audioDir = next;
    } else if (arg === "--token") {
      parsed.token = next;
    } else if (arg === "--api-base-url") {
      parsed.apiBaseUrl = next;
    } else if (arg === "--refresh-mode") {
      parsed.refreshMode = next;
    } else {
      throw new Error(`Unknown option ${arg}`);
    }

    index += 1;
  }

  return parsed;
};

const normalizeHeader = (value) => value.trim().toLowerCase().replace(/[^a-z0-9]+/g, "");

const parseCsv = (input) => {
  const rows = [];
  let row = [];
  let cell = "";
  let quoted = false;

  for (let index = 0; index < input.length; index += 1) {
    const char = input[index];
    const next = input[index + 1];

    if (quoted && char === "\"" && next === "\"") {
      cell += "\"";
      index += 1;
      continue;
    }

    if (char === "\"") {
      quoted = !quoted;
      continue;
    }

    if (!quoted && char === ",") {
      row.push(cell);
      cell = "";
      continue;
    }

    if (!quoted && (char === "\n" || char === "\r")) {
      if (char === "\r" && next === "\n") {
        index += 1;
      }
      row.push(cell);
      if (row.some((value) => value.trim())) {
        rows.push(row);
      }
      row = [];
      cell = "";
      continue;
    }

    cell += char;
  }

  row.push(cell);
  if (row.some((value) => value.trim())) {
    rows.push(row);
  }

  const headers = rows[0]?.map(normalizeHeader) ?? [];
  return rows.slice(1).map((values) => Object.fromEntries(headers.map((header, index) => [header, values[index] ?? ""])));
};

const getAny = (row, keys) => {
  for (const key of keys) {
    const value = row[normalizeHeader(key)];
    if (typeof value === "string" && value.trim()) {
      return value.trim();
    }
  }

  return null;
};

const parseBoolean = (value, fallback = false) => {
  if (!value) {
    return fallback;
  }

  return ["true", "yes", "y", "1", "required", "attribution required"].includes(value.trim().toLowerCase());
};

const parseDurationSeconds = (value) => {
  if (!value) {
    return null;
  }

  if (/^\d+$/u.test(value.trim())) {
    return Number(value.trim());
  }

  const parts = value.split(":").map((part) => Number(part.trim()));
  if (parts.some((part) => !Number.isFinite(part))) {
    return null;
  }

  return parts.reduce((total, part) => (total * 60) + part, 0);
};

const normalizeGenre = (value) => {
  if (typeof value !== "string" || !value.trim()) {
    return null;
  }

  const normalized = value
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9 &/-]+/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 80);

  return normalized.length > 0 ? normalized : null;
};

const safeHttpUrl = (value) => {
  if (typeof value !== "string" || !value.trim()) {
    return null;
  }

  try {
    const url = new URL(value.trim());
    return url.protocol === "http:" || url.protocol === "https:" ? url.toString() : null;
  } catch {
    return null;
  }
};

const assertCompletePreparedTrack = (track, index) => {
  const label = `track[${index}] ${track?.externalId ?? "<missing externalId>"}`;
  const audio = track?.audio;
  const sha256 = typeof audio?.sha256 === "string" ? audio.sha256.trim().toLowerCase() : null;
  const storageRef = typeof audio?.storageRef === "string" ? audio.storageRef.trim() : null;
  const storageRefMatch = storageRef ? musicAudioStorageRefPattern.exec(storageRef) : null;
  const genre = normalizeGenre(track?.genre);
  const vocalsClass = typeof track?.vocalsClass === "string" ? track.vocalsClass.trim().toLowerCase() : "";
  const downloadedAt = typeof track?.downloadedAt === "string" ? Date.parse(track.downloadedAt) : Number.NaN;
  const proofUrl = safeHttpUrl(track?.proof?.url);
  const studioEvidence = track?.studioEvidence;
  const studioProofUrl = safeHttpUrl(studioEvidence?.proofUrl);
  const studioSourceUrl = safeHttpUrl(studioEvidence?.sourceUrl);

  if (!track?.externalId || !track.title || !track.artist) {
    throw new Error(`${label} is missing title, artist, or externalId.`);
  }
  if (!Number.isInteger(track.durationSeconds) || track.durationSeconds <= 0) {
    throw new Error(`${label} is missing positive durationSeconds.`);
  }
  if (!Number.isFinite(downloadedAt)) {
    throw new Error(`${label} is missing downloadedAt.`);
  }
  if (!genre || genre !== track.genre) {
    throw new Error(`${label} must carry a normalized genre.`);
  }
  if (!safeVocalsClasses.has(vocalsClass)) {
    throw new Error(`${label} must carry vocalsClass none or minimal.`);
  }
  if (track.liveSafe !== true || track.vodSafe !== true) {
    throw new Error(`${label} must be liveSafe and vodSafe.`);
  }
  if (!track.attributionRequired || typeof track.attributionText !== "string" || !track.attributionText.trim()) {
    throw new Error(`${label} is missing required attribution.`);
  }
  if (!(typeof track.licenseName === "string" && track.licenseName.toLowerCase().includes("creative commons"))
    || !(typeof track.licenseUrl === "string" && track.licenseUrl.toLowerCase().startsWith(ccBy4Url))) {
    throw new Error(`${label} must have item-scoped CC BY 4.0 license evidence.`);
  }
  if (!proofUrl || !studioEvidence?.dialogText || !studioEvidence.attributionText || !studioEvidence.licenseText
    || !studioEvidence.sourceText || !studioProofUrl || !studioSourceUrl || proofUrl !== studioProofUrl) {
    throw new Error(`${label} is missing item-scoped proof evidence.`);
  }
  if (!sha256 || !sha256Pattern.test(sha256) || !storageRefMatch || storageRefMatch[1] !== sha256) {
    throw new Error(`${label} must have deterministic SHA-addressed storageRef.`);
  }
  if (typeof audio?.mimeType !== "string" || !audio.mimeType.toLowerCase().startsWith("audio/")) {
    throw new Error(`${label} is missing audio MIME evidence.`);
  }
};

const assertCompletePreparedManifest = (manifest) => {
  if (manifest?.manifestVersion !== manifestVersion || manifest.source !== "youtube-studio" || !Array.isArray(manifest.tracks)) {
    throw new Error("Manifest must be a YouTube Audio Library typed manifest.");
  }

  const seenSha256 = new Set();
  for (const [index, track] of manifest.tracks.entries()) {
    assertCompletePreparedTrack(track, index);
    const sha256 = track.audio.sha256.trim().toLowerCase();
    if (seenSha256.has(sha256)) {
      throw new Error(`Duplicate audio content rejected for sha256 ${sha256}.`);
    }
    seenSha256.add(sha256);
  }
};

const mimeTypeForFile = (filename) => {
  const extension = path.extname(filename).toLowerCase();

  if (extension === ".mp3") {
    return "audio/mpeg";
  }
  if (extension === ".m4a") {
    return "audio/mp4";
  }
  if (extension === ".wav") {
    return "audio/wav";
  }
  if (extension === ".ogg") {
    return "audio/ogg";
  }
  if (extension === ".flac") {
    return "audio/flac";
  }

  return "audio/mpeg";
};

const toTypedTrack = (row) => {
  if (row && typeof row === "object" && "externalId" in row && "title" in row) {
    return row;
  }

  const externalId = getAny(row, ["external id", "externalId", "id", "track id", "trackId", "url", "source id"]);
  const title = getAny(row, ["title", "track title", "song"]);
  const artist = getAny(row, ["artist", "author", "creator", "channel"]);
  const licenseName = getAny(row, ["license", "license name", "license type"]) ?? "";
  const attribution = getAny(row, ["attribution", "attribution text", "credit", "credits"]);
  const attributionRequired = parseBoolean(
    getAny(row, ["attribution required", "attributionRequired"]),
    licenseName.toLowerCase().includes("creative commons")
  );

  return {
    externalId,
    title,
    artist,
    durationSeconds: parseDurationSeconds(getAny(row, ["duration", "length", "duration seconds", "durationSeconds"])),
    downloadedAt: getAny(row, ["downloaded at", "downloadedAt", "download timestamp", "downloaded timestamp"]),
    genre: normalizeGenre(getAny(row, ["genre", "genres"])),
    vocalsClass: getAny(row, ["vocals class", "vocalsClass", "vocals", "vocal class"])?.toLowerCase() ?? "unknown",
    liveSafe: parseBoolean(getAny(row, ["live safe", "liveSafe"]), false),
    vodSafe: parseBoolean(getAny(row, ["vod safe", "vodSafe"]), false),
    licenseName,
    licenseUrl: getAny(row, ["license url", "licenseUrl"]) ?? "https://creativecommons.org/licenses/by/4.0/",
    attributionRequired,
    attributionText: attribution,
    proof: {
      url: getAny(row, ["proof url", "studio url", "source page", "proofUrl"])
    },
    studioEvidence: {
      studioUrl: getAny(row, ["studio url", "studioUrl", "studio page", "youtube studio url"]),
      dialogText: getAny(row, ["dialog text", "studio dialog text", "dialogText"]),
      attributionText: getAny(row, ["dialog attribution", "studio attribution", "attribution text", "attributionText"]),
      licenseText: getAny(row, ["dialog license", "license text", "licenseText"]),
      sourceText: getAny(row, ["dialog source", "source text", "sourceText"]),
      sourceUrl: getAny(row, ["source url", "proof url", "studio url", "source page", "sourceUrl"]),
      proofUrl: getAny(row, ["proof url", "studio url", "source page", "proofUrl"])
    },
    genres: (getAny(row, ["genre", "genres"]) ?? "").split(";").map((value) => value.trim()).filter(Boolean),
    moods: (getAny(row, ["mood", "moods"]) ?? "").split(";").map((value) => value.trim()).filter(Boolean),
    tags: (getAny(row, ["tags"]) ?? "").split(";").map((value) => value.trim()).filter(Boolean),
    fileName: getAny(row, ["file", "file name", "filename", "local file", "downloaded file"])
  };
};

const manifestHasCompleteFullEvidence = (manifest) => {
  const completeness = manifest?.exportCompleteness;
  return manifest?.refreshMode === "full"
    && completeness?.reachedEnd === true
    && completeness?.hitMaxTracks === false
    && completeness?.skippedCandidates === 0
    && completeness?.tracksExported > 0
    && completeness?.tracksExported === manifest.tracks.length
    && completeness?.processedCandidates === completeness.tracksExported
    && completeness?.candidateRows === completeness.tracksExported
    && completeness?.filterApplied === true
    && completeness?.refreshMode === "full";
};

const readInputManifest = async (manifestPath, refreshModeOverride) => {
  const raw = await readFile(manifestPath, "utf8");
  const parsed = manifestPath.toLowerCase().endsWith(".csv")
    ? parseCsv(raw)
    : JSON.parse(raw);

  if (parsed?.manifestVersion === manifestVersion && Array.isArray(parsed.tracks)) {
    const manifest = {
      ...parsed,
      refreshMode: refreshModeOverride ?? parsed.refreshMode
    };

    if (manifest.refreshMode === "full" && !manifestHasCompleteFullEvidence(manifest)) {
      throw new Error("Full refresh requires positive Studio exporter completeness evidence.");
    }

    return manifest;
  }

  const rows = Array.isArray(parsed) ? parsed : parsed.tracks;
  if (!Array.isArray(rows)) {
    throw new Error("Manifest must be a typed JSON manifest, a JSON array, or a CSV file.");
  }
  if (refreshModeOverride === "full") {
    throw new Error("Ad hoc CSV/JSON input cannot be imported as a full refresh without Studio exporter completeness evidence.");
  }

  return {
    manifestVersion,
    source: "youtube-studio",
    refreshMode: refreshModeOverride ?? "partial",
    exportedAt: new Date().toISOString(),
    tracks: rows.map(toTypedTrack)
  };
};

const findAudioFiles = async (audioDir) => {
  const entries = await readdir(audioDir, { recursive: true, withFileTypes: true });
  const files = new Map();

  for (const entry of entries) {
    if (!entry.isFile()) {
      continue;
    }

    const fullPath = path.join(entry.parentPath, entry.name);
    files.set(entry.name.toLowerCase(), fullPath);
  }

  return files;
};

const postJson = async (baseUrl, urlPath, token, payload) => {
  const response = await fetch(new URL(urlPath, baseUrl), {
    method: "POST",
    headers: {
      "authorization": `Bearer ${token}`,
      "content-type": "application/json"
    },
    body: JSON.stringify(payload)
  });
  const body = await response.json().catch(() => null);

  if (!response.ok) {
    throw new Error(`${urlPath} failed with ${response.status}: ${JSON.stringify(body)}`);
  }

  return body;
};

const attachUploads = async (manifest, audioDir, baseUrl, token, shouldUpload) => {
  if (!shouldUpload) {
    return manifest;
  }

  if (!audioDir) {
    throw new Error("--audio-dir is required unless --no-upload is used.");
  }

  const audioFiles = await findAudioFiles(audioDir);
  const tracks = [];

  for (const track of manifest.tracks) {
    if (track.audio?.storageRef && track.audio?.sha256) {
      tracks.push(track);
      continue;
    }

    const fileName = typeof track.fileName === "string" ? track.fileName.trim() : "";
    const filePath = fileName ? audioFiles.get(path.basename(fileName).toLowerCase()) : null;

    if (!filePath) {
      tracks.push(track);
      continue;
    }

    const bytes = await readFile(filePath);
    const contentType = mimeTypeForFile(filePath);
    const upload = await postJson(baseUrl, "/admin/music/imports/audio", token, {
      filename: path.basename(filePath),
      contentType,
      dataBase64: bytes.toString("base64")
    });

    if (!upload.ok) {
      throw new Error(`Audio upload failed for ${path.basename(filePath)}.`);
    }

    const localSha256 = createHash("sha256").update(bytes).digest("hex");
    if (upload.upload.sha256 !== localSha256) {
      throw new Error(`Upload checksum mismatch for ${path.basename(filePath)}.`);
    }

    tracks.push({
      ...track,
      audio: {
        storageRef: upload.upload.storageRef,
        sha256: upload.upload.sha256,
        mimeType: upload.upload.contentType
      }
    });
  }

  return {
    ...manifest,
    tracks
  };
};

const main = async () => {
  const args = parseArgs();
  const token = args.token ?? process.env.MAIKS_OWNER_BEARER_TOKEN ?? process.env.MAIKS_DEV_AUTH_TOKEN;
  const baseUrl = args.apiBaseUrl ?? apiBaseUrl;

  if (!args.manifest || !token || (args.refreshMode !== null && args.refreshMode !== "full" && args.refreshMode !== "partial")) {
    console.error(usage.trim());
    process.exit(1);
  }

  const inputManifest = await readInputManifest(args.manifest, args.refreshMode);
  const manifest = await attachUploads(inputManifest, args.audioDir, baseUrl, token, args.upload);
  assertCompletePreparedManifest(manifest);
  const endpoint = args.apply
    ? "/admin/music/imports/youtube-audio-library/apply"
    : "/admin/music/imports/youtube-audio-library/dry-run";
  const result = await postJson(baseUrl, endpoint, token, { manifest });

  console.log(JSON.stringify({
    mode: result.mode,
    summary: result.summary,
    rejectedTracks: result.rejectedTracks,
    sampleItems: result.items?.slice(0, 25) ?? []
  }, null, 2));
};

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
});
